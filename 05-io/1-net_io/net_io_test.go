package main

import (
	"bufio"
	"log"
	"net"
	"sync"
	"testing"
)

func Test_handleConn(t *testing.T) {
	// net.Pipe() создает пару виртуальных соединенных в памяти полнодуплексных сетевых соединений (in-memory duplex pipe).
	// Это стандартный идиоматичный способ тестирования сетевого кода в Go:
	// - НЕ открываются реальные порты в операционной системе (нет конфликтов "port already in use" в CI);
	// - Все происходит мгновенно в оперативной памяти;
	// - srv и cl реализуют интерфейс net.Conn точно так же, как настоящие TCP-сокеты.
	srv, cl := net.Pipe()

	// sync.WaitGroup нужен для ожидания завершения фоновой горутины сервера перед завершением теста.
	var wg sync.WaitGroup
	wg.Add(1)

	// Серверный обработчик запускается в отдельной горутине, чтобы не блокировать тестовый поток.
	go func() {
		defer wg.Done()
		defer srv.Close()

		handleConn(srv)
	}()

	// В основном потоке теста клиент отправляет команду "time\n" в виртуальный сокет.
	_, err := cl.Write([]byte("time\n"))
	if err != nil {
		log.Fatal(err)
	}

	// Чтение ответа сервера с помощью буферизированного ввода bufio.Reader.
	// Метод ReadBytes читает данные до первого символа перевода строки '\n'.
	reader := bufio.NewReader(cl)
	b, err := reader.ReadBytes('\n')
	if err != nil {
		log.Fatal(err)
	}

	// Проверяем, что сервер вернул непустую строку времени.
	if len(b) < 10 {
		t.Error("время не получено или ответ слишком короткий")
	}

	// Дожидаемся завершения горутины сервера и закрываем клиентский конец трубы.
	wg.Wait()
	cl.Close()
	t.Log("Ответ сервера:", string(b))
}
