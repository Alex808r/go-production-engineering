// Package simple демонстрирует основы модульного (unit) тестирования в Go.
package simple

// sum складывает два целых числа и возвращает их сумму.
// Функция не экспортируется (имя со строчной буквы), но доступна для тестов,
// находящихся в том же пакете (white-box testing).
func sum(a, b int) int {
	return a + b
}

