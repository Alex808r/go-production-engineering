package table

import "testing"

// Test_reverse демонстрирует идиоматичный подход Table-Driven Tests (табличные тесты).
//
// ПРЕИМУЩЕСТВА ТАБЛИЧНЫХ ТЕСТОВ В GO:
// 1. Читаемость и расширяемость: входные данные и ожидаемый результат сведены в единую таблицу.
//    Добавление нового тест-кейса (например, краевого случая) — это просто добавление одной строки в срез.
// 2. Изоляция через t.Run: каждый тест запускается как независимый субтест (subtest).
//    Если упадет один кейс, остальные продолжат выполняться.
// 3. Удобная фильтрация в CLI: можно запустить конкретный сценарий по имени подтеста:
//    `go test -v -run=Test_reverse/Кириллица_нечетной_длины`
// 4. Понятность отчетов: в консоли выводится конкретное имя провалившегося случая,
//    а не номер строчки в коде.
func Test_reverse(t *testing.T) {
	type args struct {
		s string
	}
	tests := []struct {
		name string // понятное человекочитаемое описание проверяемого сценария
		args args   // аргументы функции
		want string // ожидаемое возвращаемое значение
	}{
		{
			name: "ASCII строка четной длины",
			args: args{
				s: "string",
			},
			want: "gnirts",
		},
		{
			name: "ASCII со смешанным регистром",
			args: args{
				s: "ABCdefg",
			},
			want: "gfedCBA",
		},
		{
			name: "Пустая строка (граничное условие)",
			args: args{
				s: "",
			},
			want: "",
		},
		{
			name: "Кириллица нечетной длины (многобайтовый UTF-8)",
			args: args{
				s: "абв",
			},
			want: "вба",
		},
		{
			name: "Кириллица четной длины (многобайтовый UTF-8)",
			args: args{
				s: "абвг",
			},
			want: "гвба",
		},
	}

	for _, tt := range tests {
		// tt := tt — в Go < 1.22 это защищало от замыкания переменной цикла при t.Parallel()
		t.Run(tt.name, func(t *testing.T) {
			if got := reverse(tt.args.s); got != tt.want {
				t.Errorf("reverse(%q) = %q, want %q", tt.args.s, got, tt.want)
			}
		})
	}
}

