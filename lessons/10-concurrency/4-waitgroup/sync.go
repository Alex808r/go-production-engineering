// Package main демонстрирует синхронизацию горутин с помощью sync.WaitGroup
// и пошаговую координацию выполнения через небуферизованный канал.
package main

import (
	"fmt"
	"sync"
	"time"
)

// printN выполняет полезную работу и уведомляет WaitGroup о завершении.
//
// ВАЖНОЕ ПРАВИЛО:
// sync.WaitGroup ВСЕГДА передается по указателю (*sync.WaitGroup)!
// Внутри WaitGroup содержит специальное поле `noCopy`. Если передать его по значению,
// будет скопировано внутреннее состояние счетчика, и `wg.Wait()` в main() зависнет навсегда (дедлок)!
func printN(n int, wg *sync.WaitGroup) {
	// defer гарантирует вызов Done() даже в случае паники или раннего return
	defer wg.Done()

	time.Sleep(10 * time.Millisecond)
	fmt.Printf("Поток %d завершил работу\n", n)
}

// step1 выполняет первую фазу конвейера и отправляет сигнал во вторую фазу.
func step1(ch chan<- string) {
	time.Sleep(20 * time.Millisecond)
	ch <- "Результат шага 1: данные подготовлены"
}

// step2 ждет завершения первой фазы, читая сообщение из канала.
func step2(ch <-chan string) {
	msg := <-ch
	fmt.Printf("Шаг 2 получил: %q и начинает постобработку\n", msg)
}

func main() {
	// ========================================================================
	// 1. СИНХРОНИЗАЦИЯ N ГОРУТИН ЧЕРЕЗ SYNC.WAITGROUP
	// ========================================================================
	// WaitGroup поддерживает внутренний счетчик:
	//  - wg.Add(delta): увеличивает счетчик на delta
	//  - wg.Done(): уменьшает счетчик на 1 (эквивалент Add(-1))
	//  - wg.Wait(): блокирует текущую горутину, пока счетчик не станет равным 0
	const N = 5
	var wg sync.WaitGroup

	fmt.Println("--- 1. Синхронизация группы горутин через sync.WaitGroup ---")

	// ПРАВИЛО: wg.Add() вызывается СТРОГО ДО запуска горутины в родительском потоке!
	// Если вызвать Add внутри самой горутины, `wg.Wait()` может успеть завершиться раньше,
	// чем горутина начнет исполняться.
	wg.Add(N)
	for i := 1; i <= N; i++ {
		go printN(i, &wg)
	}

	// Ожидаем, пока все 5 горутин вызовут wg.Done()
	wg.Wait()
	fmt.Println("Все N потоков завершены.")

	// ========================================================================
	// 2. ПОШАГОВАЯ КООРДИНАЦИЯ ДВУХ ГОРОУТИН ЧЕРЕЗ КАНАЛ (Handshake)
	// ========================================================================
	// Небуферизованный канал отлично подходит для строгой упорядоченности шагов:
	// шаг 2 не начнется, пока шаг 1 не запишет данные в канал.
	fmt.Println("\n--- 2. Координация этапов через небуферизованный канал ---")
	ch := make(chan string)

	go step1(ch)
	step2(ch) // блокируется на `<-ch`, пока step1 не запишет результат
	fmt.Println("Программа успешно завершена.")
}

