// Package main демонстрирует паттерн параллельной обработки Fan-Out (Worker Pool / Пул воркеров):
// распределение задач из одного входного канала между несколькими параллельными горутинами.
package main

import (
	"fmt"
	"runtime"
	"sync"
	"time"
)

// processor — рабочий поток (worker).
// Читает задачи из входного канала `in`, обрабатывает их и отправляет результат в `out`.
// Завершается автоматически, когда канал `in` закрывается.
func processor(id int, in <-chan int, out chan<- int) {
	for val := range in {
		// Имитация ресурсоемких вычислений (CPU-bound)
		time.Sleep(10 * time.Millisecond)
		out <- val * val
	}
}

func main() {
	// ========================================================================
	// ТЕОРИЯ: ПАТТЕРН FAN-OUT (РАСПАРАЛЛЕЛИВАНИЕ)
	// ========================================================================
	// Применяется, когда:
	//  1. Поток входящих задач велик, а обработка каждой задачи занимает время.
	//  2. Количество запущенных воркеров обычно привязывается к числу доступных CPU ядер (runtime.NumCPU()).
	//  3. Задачи распределяются между воркерами автоматически благодаря общему входному каналу.

	src := make(chan int)
	res := make(chan int)

	numWorkers := runtime.NumCPU()
	fmt.Printf("--- Запуск Fan-Out пула из %d воркеров ---\n", numWorkers)

	var wg sync.WaitGroup
	wg.Add(numWorkers)

	// 1. Запуск пула воркеров (Fan-Out)
	for i := 0; i < numWorkers; i++ {
		workerID := i + 1
		go func() {
			defer wg.Done()
			processor(workerID, src, res)
		}()
	}

	// 2. Горутина-генератор задач (Producer)
	go func() {
		for i := 1; i <= 10; i++ {
			src <- i
		}
		// Закрываем входной канал, когда все задачи отправлены.
		// Это послужит сигналом для всех воркеров о завершении работы (for range in завершится).
		close(src)
	}()

	// 3. Координатор закрытия результатов
	// Ждет, пока все воркеры отработают и сделают wg.Done(), после чего закрывает канал результатов.
	go func() {
		wg.Wait()
		close(res)
	}()

	// 4. Потребитель результатов (Consumer)
	// Работает синхронно в main-потоке: читает из `res`, пока тот не закроется.
	// Это гарантирует, что программа не завершится раньше, чем будут обработаны все результаты!
	count := 0
	for val := range res {
		count++
		fmt.Printf("Результат #%d: %d\n", count, val)
	}

	fmt.Println("--- Все результаты успешно собраны ---")
}

