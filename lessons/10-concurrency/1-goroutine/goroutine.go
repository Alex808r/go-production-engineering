// Package main демонстрирует запуск горутин в Go, планировщик GMP,
// недерминированность порядка выполнения и синхронизацию.
package main

import (
	"fmt"
	"sync"
)

// printN выводит переданное число.
// Обратите внимание: возвращаемое значение функции (int), запущенной как горутина `go printN(...)`,
// полностью игнорируется рантаймом Go. Получить результат горутины можно только через
// каналы (chan) или разделяемую память с синхронизацией.
func printN(n int, wg *sync.WaitGroup) int {
	defer wg.Done()
	fmt.Printf("Горутина #%d выполнена\n", n)
	return n * 2 // это значение никуда не возвращается при вызове `go printN(...)`
}

func main() {
	// ========================================================================
	// ТЕОРИЯ: МОДЕЛЬ ПЛАНИРОВЩИКА GMP
	// ========================================================================
	// Go использует M:N планировщик в пространстве пользователя (GMP):
	//  - G (Goroutine): легковесный поток со стеком всего ~2 КБ (растет динамически).
	//  - M (Machine): реальный поток ОС (OS thread).
	//  - P (Processor): логический контекст планирования (число P = GOMAXPROCS = числу ядер CPU).
	//
	// Благодаря этому можно без проблем создавать сотни тысяч и миллионы горутин!

	const count = 10
	var wg sync.WaitGroup

	fmt.Println("--- Запуск горутин (порядок вывода не детерминирован) ---")

	// wg.Add вызывается ДО старта горутин
	wg.Add(count)

	for i := 0; i < count; i++ {
		// Передача аргумента `i` по значению копирует текущее число.
		// В Go 1.22+ переменная цикла `i` имеет область видимости итерации,
		// но явная передача аргумента в функцию — лучшая практика для ясности.
		go printN(i, &wg)
	}

	// Ожидаем завершения всех горутин.
	// Использовать time.Sleep для ожидания горутин — антипаттерн!
	wg.Wait()
	fmt.Println("--- Все горутины успешно завершились ---")
}

