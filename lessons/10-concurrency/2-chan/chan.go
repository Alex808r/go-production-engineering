// Package main демонстрирует работу с каналами в Go:
// передачу сообщений, буферизацию, чтение через comma-ok и range, а также закрытие канала (close).
//
// ГЛАВНОЕ ПРАВИЛО GO CONCURRENCY:
// "Do not communicate by sharing memory; instead, share memory by communicating."
// (Не общайтесь, делясь памятью; делитесь памятью, общаясь через каналы).
package main

import (
	"fmt"
	"time"
)

func main() {
	// ========================================================================
	// 1. НЕБУФЕРИЗОВАННЫЙ КАНАЛ (Unbuffered Channel)
	// ========================================================================
	// make(chan int) создает синхронный канал с нулевой емкостью.
	// Отправка (ch <- x) блокирует горутину-отправителя до тех пор,
	// пока другая горутина не выполнит чтение (<-ch). И наоборот.
	ch := make(chan int)

	// Горутина-производитель (Producer)
	go func() {
		for i := 1; i <= 3; i++ {
			ch <- i
			time.Sleep(50 * time.Millisecond)
		}
		// ПРАВИЛО ЗАКРЫТИЯ КАНАЛА:
		// 1. Закрывать канал должен ТОЛЬКО отправитель (тот, кто пишет в канал).
		// 2. Никогда не закрывайте канал со стороны получателя!
		// 3. Запись в закрытый канал вызывает ПАНИКУ: panic: send on closed channel.
		// 4. Повторное закрытие закрытого канала вызывает ПАНИКУ: panic: close of closed channel.
		close(ch)
	}()

	// Чтение через бесконечный цикл и comma-ok идиому:
	// val — прочитанное значение
	// ok — true, если значение получено из открытого канала; false, если канал закрыт и пуст!
	fmt.Println("--- Чтение из канала через comma-ok (val, ok := <-ch) ---")
	for {
		val, ok := <-ch
		fmt.Printf("Получено значение: %d (канал открыт: %t)\n", val, ok)
		if !ok {
			fmt.Println("Канал закрыт, завершаем чтение.")
			break
		}
	}

	// ========================================================================
	// 2. БУФЕРИЗОВАННЫЙ КАНАЛ И ЦИКЛ for val := range ch
	// ========================================================================
	// make(chan string, 3) создает асинхронный канал с буфером на 3 элемента.
	// Отправка в канал НЕ блокируется, пока в буфере есть свободное место.
	bufCh := make(chan string, 3)
	bufCh <- "сообщение 1"
	bufCh <- "сообщение 2"
	bufCh <- "сообщение 3"
	close(bufCh) // закрываем буферизованный канал

	// Цикл `for val := range bufCh` автоматически:
	//  1. Читает элементы из канала.
	//  2. Завершается САМ, когда канал закрыт (close) и весь буфер вычитан!
	fmt.Println("\n--- Чтение из буферизованного канала через for val := range ch ---")
	for val := range bufCh {
		fmt.Println("Буфер:", val)
	}

	// ========================================================================
	// ТАБЛИЦА ПОВЕДЕНИЯ КАНАЛОВ В GO:
	// ========================================================================
	// Операция         | nil-канал              | Открытый канал     | Закрытый канал
	// -----------------+------------------------+--------------------+-------------------------
	// Чтение (<-ch)    | Блокирует навсегда     | Читает/Блокирует   | Сразу zero-value, ok=false
	// Запись (ch <- v) | Блокирует навсегда     | Пишет/Блокирует    | ПАНИКА (send on closed)
	// Закрытие (close) | ПАНИКА (nil channel)   | Закрывает успешно  | ПАНИКА (close of closed)
}

