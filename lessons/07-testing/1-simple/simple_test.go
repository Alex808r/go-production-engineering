package simple

import (
	"testing"
)

// Test_sum демонстрирует базовую структуру модульного теста в Go.
//
// ПРАВИЛА И СОГЛАШЕНИЯ О ТЕСТИРОВАНИИ В GO:
// 1. Имя файла тестов должно оканчиваться на `_test.go` (компилятор Go исключает такие файлы
//    из релизной сборки приложения `go build`).
// 2. Имя тестовой функции должно начинаться со слова `Test` с заглавной буквы,
//    следующий символ не может быть строчной буквой (например: TestSum, Test_sum, TestParseURL).
// 3. Сигнатура тестовой функции строго определена: `func (t *testing.T)`.
// 4. White-box vs Black-box тестирование:
//    - `package simple` (тот же пакет) — имеет доступ к приватным (неэкспортируемым) функциям и полям.
//    - `package simple_test` (внешний пакет) — тестирует только публичный контракт пакета (API).
// 5. Разница между t.Errorf и t.Fatalf:
//    - `t.Errorf`: отмечает тест как непрошедший (Failed), логирует ошибку, но ПРОДОЛЖАЕТ выполнение.
//      Используется, когда полезно увидеть все ошибки валидации за один прогон.
//    - `t.Fatalf`: отмечает тест как непрошедший и НЕМЕДЛЕННО ПРЕРЫВАЕТ его (через runtime.Goexit).
//      Используется, когда дальнейшее выполнение бессмысленно (например, nil pointer, ошибка соединения).
// 6. t.Log / t.Logf: сообщения выводятся в консоль только при подробном запуске (`go test -v`)
//    или в случае провала теста.
func Test_sum(t *testing.T) {
	a, b := 3, 4 // входные аргументы
	want := 7    // ожидаемый результат (эталон)

	got := sum(a, b) // фактический результат выполнения тестируемой функции

	// Сравнение фактического результата с ожидаемым
	if got != want {
		t.Fatalf("sum(%d, %d) = %d; want %d", a, b, got, want)
	}

	t.Log("sum() успешно прошел проверку")
}

