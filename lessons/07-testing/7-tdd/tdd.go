// Package tdd демонстрирует разработку через тестирование (Test-Driven Development).
package tdd

// Fact вычисляет факториал натурального числа n (n!).
// По математическому определению:
// 0! = 1
// 1! = 1
// n! = n * (n-1)!
//
// Функция была написана в рамках цикла TDD:
// 1. Сначала написан тест на n=1, затем реализация return 1.
// 2. Затем тест на n=3, добавлена рекурсивная ветка n * Fact(n-1).
// 3. Затем проверен краевой случай n=0.
func Fact(n int) int {
	if n < 1 {
		return 1
	}

	return n * Fact(n-1)
}

