// Package bsearch демонстрирует сравнительное профилирование производительности
// алгоритмов поиска (бинарный vs линейный) с использованием инструментария testing.B.
package bsearch

// Binary выполняет бинарный (двоичный) поиск элемента в предварительно отсортированном срезе.
// Сложность алгоритма: O(log N).
// На массиве из 1_000_000 элементов требует не более ~20 сравнений.
// Возвращает индекс найденного элемента или -1, если элемент отсутствует.
func Binary(data []int, item int) int {
	low, high := 0, len(data)-1
	for low <= high {
		mid := (low + high) / 2
		if data[mid] == item {
			return mid
		}
		if data[mid] < item {
			low = mid + 1
		} else {
			high = mid - 1
		}
	}
	return -1
}

// Simple выполняет линейный (последовательный) перебор элементов среза.
// Сложность алгоритма: O(N).
// На массиве из 1_000_000 элементов в среднем требует ~500_000 сравнений.
// Возвращает индекс найденного элемента или -1, если элемент отсутствует.
func Simple(data []int, item int) int {
	for i := range data {
		if data[i] == item {
			return i
		}
	}
	return -1
}

