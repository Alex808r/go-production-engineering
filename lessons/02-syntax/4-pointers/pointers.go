package main

import "fmt"

func main() {
	var i int = 10 // переменная
	var p *int     // указатель
	p = &i         // взятие адреса. указателю присваивается ссылка.
	// *interface{} (или *any) — указатель на саму интерфейсную переменную, а НЕ аналог void* из C:
	//  - В реальном коде почти никогда НЕ нужен. Частая ошибка новичков — думать, что это "указатель на любой тип".
	//  - Попытка p1 = &i вызовет ошибку компиляции (*int не приводится к *interface{}).
	//  - Единственный сценарий: передача переменной-интерфейса в функцию по указателю для ее перезаписи (*p1 = "новое").
	//  - Шпаргалка:
	//      * Хранить значение любого типа -> interface{} (или any)
	//      * Универсальный указатель на память -> unsafe.Pointer
	//      * Обобщенный код -> Generics [T any]
	var p1 *interface{}
	_ = p1
	fmt.Println(i)
	i++
	fmt.Println(i)
	*p++ // разыменование указателя
	fmt.Println(i)
	*(&i)++
	fmt.Println(i)
}

// Output: 	10
//			11
//			12
//			13
