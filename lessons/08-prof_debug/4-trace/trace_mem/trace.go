// Package main демонстрирует трассировку аллокаций памяти (Heap) и работы сборщика мусора (GC).
package main

import (
	"fmt"
	"log"
	"os"
	"runtime"
	"runtime/trace"
)

// АНАЛИЗ ПАМЯТИ И СБОРКИ МУСОРА ЧЕРЕЗ GO TOOL TRACE:
//
// 1. Запуск программы для генерации файла трассировки:
//    go run trace.go
// 2. Открытие визуализатора:
//    go tool trace trace.out
//
// ЧТО ИЗУЧАТЬ НА ТАЙМЛАЙНЕ:
// - График "Heap": показывает объем активной памяти в куче (Allocated Heap) и следующий порог сборщика мусора (Next GC).
// - График "GC": отмечает фазы работы Garbage Collector:
//   * Concurrent Mark (маркировка живых объектов в фоне)
//   * STW (Stop The World): паузы остановки мира в начале и конце цикла сборки мусора (обычно < 1 мс).
//   * Mark Assist: когда горутины программы вынуждены помогать сборщику мусора при слишком высокой скорости аллокаций.
//   * Sweep: фаза освобождения памяти и возврата страниц в аллокатор mheap.
func main() {
	// Файл, в который будет сохраняться бинарный поток событий трассировки
	f, err := os.Create("trace.out")
	if err != nil {
		log.Fatalf("ошибка создания trace.out: %v", err)
	}
	defer f.Close()

	// Запуск трассировщика
	if err := trace.Start(f); err != nil {
		log.Fatalf("ошибка старта трассировки: %v", err)
	}
	defer trace.Stop()

	fmt.Println("Запись трассировки памяти и GC...")

	// Цикл 1: Выделение и очистка памяти
	nums := fillSlice()
	emptySlice(nums)

	// Принудительный вызов сборщика мусора — на таймлайне будет четко виден блок GC STW
	runtime.GC()

	// Цикл 2: Повторное выделение и очистка памяти
	nums = fillSlice()
	emptySlice(nums)

	fmt.Println("Трассировка успешно записана в trace.out. Запустите: go tool trace trace.out")
}

// fillSlice наполняет срез 100_000 элементами без предварительного выделения емкости cap.
// На графике Heap это приведет к характерной "лесенке" реалокаций кучи:
// базовый массив среза перевыделяется (каждый раз удваивая емкость, затем с коэффициентом ~1.25),
// а старые массивы становятся мусором для GC.
func fillSlice() []int {
	var nums []int
	for i := 0; i < 100_000; i++ {
		nums = append(nums, i)
	}
	return nums
}

// emptySlice удаляет элементы из конца среза.
// Конструкция append(nums[:i], nums[:i+1]...) сдвигает элементы и демонстрирует
// работу с базовым массивом среза в памяти.
func emptySlice(nums []int) {
	for i := len(nums) - 1; i >= 0; i-- {
		nums = append(nums[:i], nums[:i+1]...)
	}
}

