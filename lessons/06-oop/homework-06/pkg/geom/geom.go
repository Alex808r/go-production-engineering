// Package geom реализует вычисление геометрических характеристик на декартовой плоскости.
package geom

import (
	"math"
)

/*
================================================================================
РАЗБОР СТИЛИСТИЧЕСКИХ, АРХИТЕКТУРНЫХ И ВЫЧИСЛИТЕЛЬНЫХ ОШИБОК ИЗ hw.go
(Согласно лекции №6 "ООП в Go", Effective Go и Go Code Review Comments)
================================================================================

1. Имя получателя метода (Receiver Name):
   - БЫЛО: `func (geom Geom) CalculateDistance()` — многократное дублирование типа в имени переменной-получателя.
   - СТАЛО: `func (g Geom)` / `func (p Point)` — в Go (CodeReviewComments -> Receiver Names)
     рекомендуется использовать краткие (1-2 буквы) идентификаторы, производные от имени типа.
     Запрещены generic-имена (`this`, `self`, `me`).

2. Именование метода (Method Naming):
   - БЫЛО: `CalculateDistance()` — паразитный префикс `Calculate...`.
   - СТАЛО: `Distance()` — согласно Effective Go, геттеры и вычисляемые свойства объектов
     должны быть лаконичными существительными без избыточных глаголов (`Distance()`, `Length()`, `Area()`).

3. Сайд-эффекты и печать в stdout (Side Effects):
   - БЫЛО: `fmt.Println("Координаты не могут быть меньше нуля")` внутри чистой математической функции.
   - СТАЛО: удален побочный ввод-вывод. Пакеты уровня библиотеки не должны самовольно печатать
     диагностику в `os.Stdout`, загрязняя потоки вызывающего приложения.

4. Математическая некорректность и "магические числа":
   - БЫЛО: искусственное ограничение `geom.X1 < 0 || ...` с возвратом магического числа `-1`.
   - СТАЛО: в декартовой системе координат отрицательные значения осей (-X, -Y) абсолютно допустимы,
     а евклидово расстояние $\sqrt{\Delta X^2 + \Delta Y^2}$ математически корректно и строго неотрицательно.

5. Неэффективность вычислений:
   - БЫЛО: `math.Pow(geom.X2-geom.X1, 2)` — возведение в степень через аппроксимацию логарифмов и экспонент,
     что в ~10-20 раз медленнее прямого умножения `dx * dx`.
   - СТАЛО: использование специализированной функции `math.Hypot(dx, dy)`, которая аппаратно оптимизирована
     и математически защищена от переполнения (overflow) и потери точности при предельных значениях float64.

6. Избыточный блок `else` после терминального `return`:
   - БЫЛО: `if ... { return -1 } else { ... }`.
   - СТАЛО: соблюдение идиомы Go "Guard Clause" / "Early Return" — отказ от лишней вложенности,
     основной поток выполнения идет по левому краю без отступов.

7. Избыточный именованный результат и дублирование:
   - БЫЛО: сигнатура `(distance float64)`, присвоение `distance = ...`, затем `return distance`.
   - СТАЛО: лаконичный возврат результата выражения `return math.Hypot(dx, dy)`.

8. Архитектурная декомпозиция (ООП в стиле Go):
   - БЫЛО: монолитная структура `Geom` с 4 координатами `X1, Y1, X2, Y2` (смешение понятий "точка",
     "отрезок" и абстрактной "геометрии").
   - СТАЛО: введена элементарная сущность `Point` (точка $X, Y$) с методом `p.Distance(target Point)`.
     Для обратной совместимости сохранена структура `Geom`, делегирующая расчет методу точек.
*/

// Point представляет точку на двумерной декартовой плоскости.
type Point struct {
	X float64
	Y float64
}

// Distance вычисляет евклидово расстояние между текущей точкой p и целевой точкой target.
func (p Point) Distance(target Point) float64 {
	return math.Hypot(target.X-p.X, target.Y-p.Y)
}

// Geom представляет отрезок или две точки для расчета расстояния (обратная совместимость).
type Geom struct {
	X1, Y1, X2, Y2 float64
}

// Distance возвращает расстояние между первой и второй точками.
func (g Geom) Distance() float64 {
	p1 := Point{X: g.X1, Y: g.Y1}
	p2 := Point{X: g.X2, Y: g.Y2}
	return p1.Distance(p2)
}

// CalculateDistance сохраняет обратную совместимость со старым API задания.
func (g Geom) CalculateDistance() float64 {
	return g.Distance()
}
