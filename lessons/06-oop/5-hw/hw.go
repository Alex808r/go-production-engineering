package hw

import (
	"math"
)

/*
СПИСОК ИСПРАВЛЕННЫХ СТИЛИСТИЧЕСКИХ И АРХИТЕКТУРНЫХ НЕДОСТАТКОВ:
1. Имя получателя метода (Receiver Name):
   - Было: `func (geom Geom)` — повторение имени типа, слишком длинное имя.
   - Стало: `func (g Geom)` / `func (p Point)` — в Go (согласно Go Code Review Comments)
     принято использовать краткие 1-2 буквенные имена ресиверов, отражающие имя типа.

2. Именование метода (Method Name):
   - Было: `CalculateDistance()` — неидиоматичный префикс `Calculate`.
   - Стало: `Distance()` — в Go приняты лаконичные имена (согласно Effective Go).

3. Вывод в стандартный поток (Side-Effects / fmt.Println):
   - Было: `fmt.Println("Координаты не могут быть меньше нуля")` внутри вычислительной функции.
     Библиотечный пакет не должен засорять stdout приложения.
   - Стало: убран побочный ввод-вывод.

4. Математическая некорректность и "магические числа":
   - Было: ограничение `< 0` и возврат магического значения `-1`.
     На декартовой плоскости отрицательные координаты абсолютно корректны,
     а евклидово расстояние всегда неотрицательно.
   - Стало: расчет корректен для любых координат на вещественной плоскости.

5. Неэффективность вычислений:
   - Было: `math.Pow(dx, 2)` — возведение в степень через логарифмы/экспоненты,
     что в десятки раз медленнее умножения.
   - Стало: использование стандартной функции `math.Hypot(dx, dy)` или прямого `dx*dx + dy*dy`.
     `math.Hypot` аппаратно защищает от переполнения (overflow) и потери точности при больших значениях.

6. Избыточный блок `else` после `return`:
   - Было: ветвление `if ... return -1 } else { ... }`.
   - Стало: плоская структура кода (Early return / Guard clause).

7. Именованный возврат и лишние переменные:
   - Было: именованный результат `(distance float64)`, присвоение `distance = ...`,
     затем `return distance`.
   - Стало: чистый возврат значения выражения `return math.Hypot(dx, dy)`.

8. Декомпозиция предметной области (DDD / Идиоматичное ООП в Go):
   - Было: монолитная структура `Geom` с 4 полями `X1, Y1, X2, Y2`.
   - Стало: введена атомарная сущность `Point` (точка с координатами X, Y)
     и метод `Distance(p2 Point) float64`. Для обратной совместимости сохранена
     структура `Geom` и метод `CalculateDistance()`, делегирующий расчет точкам.
*/

// Point представляет точку на двумерной плоскости с координатами X и Y.
type Point struct {
	X float64
	Y float64
}

// Distance вычисляет евклидово расстояние между текущей точкой p и целевой точкой target.
// Использует функцию math.Hypot, защищающую от переполнения и потери точности.
func (p Point) Distance(target Point) float64 {
	return math.Hypot(target.X-p.X, target.Y-p.Y)
}

// Geom представляет отрезок или пару точек для расчета расстояния.
// Сохранена для обратной совместимости со старым API.
type Geom struct {
	X1, Y1, X2, Y2 float64
}

// Distance возвращает расстояние между точками (X1, Y1) и (X2, Y2).
func (g Geom) Distance() float64 {
	p1 := Point{X: g.X1, Y: g.Y1}
	p2 := Point{X: g.X2, Y: g.Y2}
	return p1.Distance(p2)
}

// CalculateDistance сохраняет обратную совместимость с первоначальным интерфейсом задачи.
func (g Geom) CalculateDistance() float64 {
	return g.Distance()
}
