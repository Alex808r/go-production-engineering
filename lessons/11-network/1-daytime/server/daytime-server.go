// Package main реализует сервер текущего времени в соответствии с протоколом Daytime (RFC 867).
//
// ТЕОРИЯ: СЕТЕВЫЕ ПОРТЫ В ОПЕРАЦИОННЫХ СИСТЕМАХ
// 1. Привилегированные порты (0–1023): требуют прав администратора (root/sudo).
//    Исторический порт службы Daytime — 13.
// 2. Пользовательские (непривилегированные) порты (1024–49151): могут открываться
//    любым обычным процессом без sudo. Для учебного запуска используем порт :1313.
// 3. Динамические/эфемеридные порты (49152–65535): выделяются ОС для исходящих клиентов.
package main

import (
	"fmt"
	"io"
	"log"
	"net"
	"time"
)

const listenAddr = "0.0.0.0:1313"

// handler обрабатывает подключение одного клиента.
// В качестве параметра принимает интерфейс io.ReadWriteCloser,
// которому удовлетворяет конкретное сетевое соединение net.Conn.
func handler(conn io.ReadWriteCloser) {
	defer conn.Close()

	// Форматируем текущее время сервера
	daytime := time.Now().Format(time.RubyDate) + "\n"

	// Записываем время в сетевой поток клиента
	_, err := conn.Write([]byte(daytime))
	if err != nil {
		log.Printf("Ошибка отправки клиенту: %v", err)
	}
}

func main() {
	// ========================================================================
	// 1. РЕГИСТРАЦИЯ СЛУЖБЫ ЧЕРЕЗ net.Listen
	// ========================================================================
	// "tcp4" — протокол IPv4.
	// "0.0.0.0:1313" — привязка ко всем сетевым интерфейсам (localhost, локальная сеть, Wi-Fi).
	// Если указать "127.0.0.1:1313", сервер будет доступен ТОЛЬКО локально с этого компьютера.
	listener, err := net.Listen("tcp4", listenAddr)
	if err != nil {
		log.Fatalf("Ошибка запуска Daytime сервера на %s: %v", listenAddr, err)
	}
	defer listener.Close()

	fmt.Printf("Daytime сервер (RFC 867) успешно запущен и слушает на %s\n", listenAddr)
	fmt.Println("Для проверки выполните: go run ./11-network/1-daytime/client/daytime-client.go")

	// ========================================================================
	// 2. ЦИКЛ ПРИЕМА ПОДКЛЮЧЕНИЙ (ACCEPT LOOP)
	// ========================================================================
	for {
		// listener.Accept() блокирует горутину до появления нового клиентского TCP-подключения
		conn, err := listener.Accept()
		if err != nil {
			log.Printf("Ошибка при приеме соединения: %v", err)
			continue
		}

		// ВАЖНО: Каждого клиента обрабатываем в ОТДЕЛЬНОЙ горутине (go handler(conn)),
		// чтобы медленный клиент не блокировал цикл Accept для остальных клиентов!
		go handler(conn)
	}
}

