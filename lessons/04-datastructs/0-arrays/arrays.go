package main

import (
	"fmt"

	"github.com/DmitriyVTitov/size"
)

// Пример демонстрирует ключевые аспекты работы со срезами (slices) в Go:
// 1. Потребление памяти большими срезами при копировании (риск удвоения памяти и OOM).
// 2. Механизм разделяемого базового массива (shared underlying array) и побочные эффекты среза от среза.
// 3. Разрыв связи между срезами при нехватке cap и реаллокации базового массива через append().

const N = 1_000_000_000 // 1 миллиард элементов

// В 64-битной ОС один элемент типа int занимает 8 байт.
// 1_000_000_000 * 8 байт = 8_000_000_000 байт ≈ 7.45 ГБ оперативной памяти.
var slice = make([]int, N)

func main() {
	// --- ЧАСТЬ 1: УДВОЕНИЕ ПАМЯТИ ПРИ КОПИРОВАНИИ (Ручной аналог append) ---
	// Строки ниже наглядно демонстрируют, что происходит "под капотом" append(slice, 25),
	// когда текущей вместимости (cap) не хватает:
	// 1. Выделяется новый базовый массив на 1 элемент больше (аллоцирует ЕЩЕ ~7.45 ГБ памяти).
	newSlice := make([]int, N+1)
	// 2. Старые данные копируются из исходного среза в новый.
	copy(newSlice, slice)
	// 3. Значение 25 записывается в добавленный последний элемент.
	//    Индекс len-1 адресует самый последний элемент (в Go нет отрицательных индексов вроде [-1]).
	newSlice[len(newSlice)-1] = 25

	// Демонстрация ручного заполнения среза в цикле (~8 МБ в памяти):
	// В отличие от встроенной функции copy() (которая копирует память блоками через ассемблерный memmove),
	// ручное заполнение требует миллиона итераций процессора.
	// Конструкция "_ = s" подавляет ошибку неиспользуемой переменной; после этого s доступен для сборщика мусора (GC).
	s := make([]int, 1_000_000)
	for i := 0; i < 1_000_000; i++ {
		s[i] = i
	}
	_ = s

	// Демонстрация изоляции копий после функции copy():
	// Изменение newSlice[1] = 10 НЕ затрагивает исходный slice[1] (он остался равным 0),
	// так как copy создал полностью независимый базовый массив в памяти.
	// (Сравните с Частью 2 ниже, где срез от среза делит один и тот же массив).
	newSlice[1] = 10

	// Оценка объема занимаемой памяти с помощью сторонней библиотеки size.
	// На момент одновременного существования slice и newSlice суммарный объем RAM ≈ 14-15 ГБ!
	// Вывод: наивное расширение среза через создание нового и copy() временно требует x2 памяти.
	x, y := size.Of(slice), size.Of(newSlice)
	fmt.Printf("Size of 'slice' is %vGB\n", x/1024/1024/1024)
	fmt.Printf("Size of 'newSlice' is %vGB\n", y/1024/1024/1024)
	fmt.Printf("Size of both slices is %vGB\n", (x+y)/1024/1024/1024)

	// --- ЧАСТЬ 2: РАЗДЕЛЯЕМЫЙ БАЗОВЫЙ МАССИВ (Shared Underlying Array) ---
	// Срез в Go — это легковесный заголовок (указатель на массив, len, cap).
	s1 := []int{1, 2, 3, 4, 5}

	// s2 — это срез от s1 (элементы с индексами [1:3], т.е. s1[1] и s1[2]).
	// Данные НЕ копируются! s2 ссылается на ТЕ ЖЕ ячейки памяти базового массива, что и s1.
	s2 := s1[1:3] // {2, 3}
	fmt.Println("s2:", s2)
	fmt.Println("s1 before:", s1)

	// Изменение элемента в s2[0] напрямую меняет значение в s1[1],
	// поскольку они делят один и тот же базовый массив в памяти (побочный эффект / side effect).
	s2[0] = 10
	fmt.Println("s1 after:", s1) // выведет: [1 10 3 4 5]

	// --- ЧАСТЬ 3: РАЗРЫВ СВЯЗИ ПРИ ПРЕВЫШЕНИИ ЕМКОСТИ (cap) ---
	// У s2 длина len=2, но емкость cap=4 (считается от индекса 1 до конца s1).
	// Пока добавление укладывается в cap, append продолжает писать в ОБЩИЙ базовый массив:
	s2 = append(s2, 99) // перезапишет s1[3] (было 4, станет 99)!
	fmt.Println("\nПосле append в пределах cap(s2):")
	fmt.Println("s2:", s2, "len:", len(s2), "cap:", cap(s2))
	fmt.Println("s1:", s1) // [1 10 3 99 5] — s1 затронут!

	// Когда емкости cap(s2) больше не хватает, append выделяет НОВЫЙ базовый массив:
	s2 = append(s2, 100, 200) // превысили cap=4 -> реаллокация!
	fmt.Println("\nПосле append сверх cap(s2) (выделен новый массив):")
	fmt.Println("s2:", s2, "len:", len(s2), "cap:", cap(s2))

	// Теперь связь разорвана: любые мутации в s2 больше НЕ влияют на s1!
	s2[0] = 777
	fmt.Println("s2 после s2[0]=777:", s2)
	fmt.Println("s1 после s2[0]=777:", s1) // s1 остался [1 10 3 99 5] (не изменился)
}
