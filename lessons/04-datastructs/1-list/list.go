// Реализуация двусвязного списка вместе с базовыми операциями.
package list

import (
	"fmt"
)

// List — кольцевой двусвязный список с фиктивным (сторожевым / sentinel) элементом root.
// Использование фиктивного корня позволяет избежать постоянных проверок на nil
// при добавлении и удалении граничных элементов.
type List struct {
	root *Elem // Сторожевой элемент. Сам не хранит пользовательских данных.
}

// Elem — узел (элемент) двусвязного списка.
type Elem struct {
	Val        interface{} // Полезная нагрузка (значение элемента)
	next, prev *Elem       // Указатели на следующий и предыдущий элементы
}

// New создаёт пустой список и инициализирует сторожевой узел.
// В пустом кольцевом списке корень замыкается сам на себя: root.next = root и root.prev = root.
func New() *List {
	var l List
	l.root = &Elem{}
	l.root.next = l.root
	l.root.prev = l.root
	return &l
}

// Push вставляет новый элемент в НАЧАЛО списка (сразу после l.root) за O(1).
func (l *List) Push(e Elem) *Elem {
	// 1. Связываем новый элемент:
	//    - его prev указывает на корень (он становится первым элементом);
	//    - его next указывает на бывший первый элемент (l.root.next).
	e.prev = l.root
	e.next = l.root.next

	// 2. Корень теперь указывает на новый элемент как на первый.
	l.root.next = &e

	// 3. Обновляем обратную связь у соседа справа:
	if e.next != l.root {
		// Если в списке уже были элементы, бывший первый элемент должен ссылаться на &e как на prev.
		e.next.prev = &e
	} else {
		// Если список был пуст, новый элемент одновременно является и первым, и последним:
		// замыкаем l.root.prev на него (хвост списка).
		l.root.prev = &e
	}
	return &e
}

// String реализует интерфейс fmt.Stringer, обходя список от головы к хвосту за O(N).
func (l *List) String() string {
	el := l.root.next
	var s string
	// Идем по кольцу вперед, пока снова не упремся в сторожевой узел l.root
	for el != l.root {
		s += fmt.Sprintf("%v ", el.Val)
		el = el.next
	}
	// Убираем хвостовой пробел
	if len(s) > 0 {
		s = s[:len(s)-1]
	}
	return s
}

// Pop удаляет первый элемент списка (голову) за O(1).
func (l *List) Pop() *List {
	// Проверка на nil или пустой список (когда root указывает сам на себя)
	if l == nil || l.root == nil || l.root.next == l.root {
		return l
	}

	// 1. Запоминаем текущий первый элемент
	first := l.root.next

	// 2. Исключаем first из цепочки: корень теперь указывает сразу на следующий за ним элемент
	l.root.next = first.next
	first.next.prev = l.root

	// 3. Если после удаления список опустел, восстанавливаем указатель хвоста root.prev на сам корень
	if l.root.next == l.root {
		l.root.prev = l.root
	}

	return l
}

// Reverse разворачивает двусвязный список на месте за O(N) времени и O(1) памяти.
// Алгоритм меняет местами указатели next и prev у каждого узла.
func (l *List) Reverse() *List {
	// Если список пустой или не инициализирован — разворачивать нечего
	if l == nil || l.root == nil || l.root.next == l.root {
		return l
	}

	curr := l.root.next     // начинаем с первого реального элемента (головы)
	var prev *Elem = l.root // предыдущим узлом для первого элемента изначально является root

	// Обходим все реальные узлы списка до тех пор, пока не вернемся в root
	for curr != l.root {
		next := curr.next // 1. Запоминаем оригинальный следующий узел, чтобы не потерять связь
		curr.next = prev  // 2. Разворачиваем стрелку next: теперь она указывает назад (на prev)
		curr.prev = next  // 3. Разворачиваем стрелку prev: теперь она указывает вперед (на оригинальный next)
		prev = curr       // 4. Сдвигаем prev вперед (текущий узел становится "предыдущим" для следующей итерации)
		curr = next       // 5. Переходим к следующему узлу
	}

	// Корректируем сторожевой узел root после полного разворота:
	// - Бывший первый элемент (l.root.next) стал самым последним элементом (новым хвостом).
	// - Узел prev (бывший последний элемент) стал новым первым элементом (новой головой).
	oldHead := l.root.next
	l.root.next = prev
	l.root.prev = oldHead

	return l
}

