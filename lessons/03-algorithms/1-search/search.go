package bsearch

import "fmt"

// Simple возвращает индекс элемента в слайсе или -1. Используется линейный поиск.
// Работает на любых (в том числе неотсортированных) слайсах.
// Временная сложность: O(N), дополнительная память: O(1).
func Simple(data []int, item int) int {
	for i := range data {
		if data[i] == item {
			return i
		}
	}
	return -1
}

// Binary возвращает индекс элемента в слайсе или -1. Используется бинарный поиск.
// ВАЖНО: работает ТОЛЬКО для отсортированных слайсов (в данном случае — по возрастанию).
// Если слайс не отсортирован, алгоритм даст некорректный результат (-1), так как
// опирается на предположение, что элементы упорядочены, и отбрасывает половину данных.
// Временная сложность: O(log N), дополнительная память: O(1).
// Примечание: вычисление mid := low + (high-low)/2 предотвращает целочисленное
// переполнение при больших массивах (в отличие от (low + high) / 2).
func Binary(data []int, item int) int {
	low, high := 0, len(data)-1
	for low <= high {
		mid := low + (high-low)/2
		if data[mid] == item {
			return mid
		}
		if data[mid] < item {
			low = mid + 1
		} else {
			high = mid - 1
		}
	}
	return -1
}

// O демонстрирует типовые классы временной сложности алгоритмов (Big O notation).
func O() {
	slice := []int{1, 2, 3}

	// O(1) — Константная сложность:
	// Операция не зависит от размера данных. В Go чтение len(slice) — это мгновенное
	// чтение поля Len из структуры SliceHeader в памяти (1 операция процессора).
	fmt.Println(len(slice))

	// O(log N) — Логарифмическая сложность:
	// На каждом шаге область поиска делится пополам (либо шаг умножается на 2).
	// Например, бинарный поиск Binary(slice, 2) или цикл с удвоением шага:
	// для N = 1024 цикл выполнится всего 10 раз (log2(1024) = 10).
	for i := 1; i < len(slice); i *= 2 {
		_ = i
	}
	_ = Binary(slice, 2)

	// O(N) — Линейная сложность:
	// Время выполнения прямо пропорционально количеству элементов N = len(slice).
	// Один проход по массиву/слайсу.
	for i := range slice {
		// ....

		// O(N^2) — Квадратичная сложность:
		// Вложенный цикл: для каждого из N элементов выполняется N итераций (N * N).
		// Характерно для простых сортировок (пузырьковая, вставками, выбором).
		for j := range slice {

			// O(N^3) — Кубическая сложность:
			// Три вложенных цикла: N * N * N операций.
			// Быстро деградирует по времени при росте N (например, наивное умножение матриц).
			for k := range slice {
				_, _, _ = i, j, k
			}
		}
	}
}
