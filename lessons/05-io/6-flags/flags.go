package main

import (
	"flag"
	"fmt"
)

func main() {
	// flag.String регистрирует строковый флаг и возвращает указатель (*string).
	// Параметры: (имя флага, значение по умолчанию, текст справки).
	s := flag.String("filename", "file.txt", "имя файла")

	// flag.IntVar привязывает флаг к уже объявленной переменной n.
	// Демонстрация алиасов: два флага (-n и -number) привязаны к ОДНОЙ переменной n,
	// позволяя пользователю передать как короткую, так и длинную форму флага.
	var n int
	flag.IntVar(&n, "n", 10, "количество (короткая форма)")
	flag.IntVar(&n, "number", 10, "количество (длинная форма)")

	// КРИТИЧЕСКИ ВАЖНО: flag.Parse() выполняет фактический разбор аргументов os.Args[1:].
	// До вызова flag.Parse() все переменные флагов содержат только значения по умолчанию!
	flag.Parse()

	// flag.PrintDefaults() выводит в stderr форматированное описание всех зарегистрированных флагов.
	fmt.Println("--- Зарегистрированные флаги (PrintDefaults): ---")
	flag.PrintDefaults()

	// Обращение к значениям: *s через разыменование указателя, n напрямую по значению.
	fmt.Printf("\nРезультат: filename=%s, n=%d\n", *s, n)
}
