package stringutils

// Rev возвращает перевёрнутую строку s с корректной поддержкой Unicode/UTF-8.
func Rev(s string) string {
	runes := []rune(s)

	for i, j := 0, len(runes)-1; i < j; i, j = i+1, j-1 {
		runes[i], runes[j] = runes[j], runes[i]
	}

	return string(runes)
}

/*
Пояснения к работе функции:

1. Зачем преобразуем в срез рун — []rune(s)?
   - В Go тип string — это неизменяемая (immutable) последовательность байт ([]byte),
     закодированная в UTF-8.
   - Символы ASCII (латиница, цифры) занимают 1 байт, но символы других алфавитов
     (например, кириллица) занимают 2 байта, а эмодзи — до 4 байт.
   - Если бы мы переворачивали строку побайтово ([]byte), байты многобайтовых символов
     поменялись бы местами, нарушилась бы кодировка UTF-8, и вместо букв получились бы
     нечитаемые символы («кракозябры»).
   - rune в Go — это псевдоним int32, представляющий одну кодовую точку Unicode (один символ).
   - Преобразование []rune(s) декодирует строку UTF-8 в срез отдельных символов.
   - 8080мым (mutable), что позволяет менять элементы местами.

2. Как работает цикл разворота (for i, j := 0, len(runes)-1; i < j; i, j = i+1, j-1)?
   - Используется классический алгоритм «двух указателей»:
     - i указывает на начало среза и двигается вправо (i = i + 1).
     - j указывает на конец среза и двигается влево (j = j - 1).
   - runes[i], runes[j] = runes[j], runes[i] — множественное присваивание в Go,
     которое меняет два элемента местами без необходимости заводить временную переменную.
   - Цикл останавливается, когда указатели встречаются в середине (i >= j).

3. Зачем преобразуем обратно в строку — string(runes)?
   - Функция Rev возвращает тип string, а работа велась со срезом []rune.
   - Выражение string(runes) кодирует срез кодовых точек Unicode обратно в компактную
     неизменяемую UTF-8 строку для возврата вызывающему коду.
*/
