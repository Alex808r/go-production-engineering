// Package main разбирает задачу на оценку занимаемой памяти (Memory Layout)
// структурами в Go, выравнивание полей (memory alignment), паддинг (padding)
// и разницу между поверхностным (shallow) и глубоким (deep) размером объекта.
package main

import (
	"fmt"
	"unsafe"

	"github.com/DmitriyVTitov/size"
)

// Структура example содержит поля разных типов.
// На 64-битной архитектуре (arm64, amd64) машинное слово равно 8 байтам.
type example struct {
	a []int  // Заголовок среза: 24 байта (указатель 8 байт, len 8 байт, cap 8 байт)
	b bool   // Логический тип: 1 байт
	c int32  // 32-битное целое: 4 байта (требует выравнивания по границе 4 байт)
	d string // Заголовок строки: 16 байт (указатель 8 байт, len 8 байт)
}

func main() {
	// =========================================================================
	// 1. Поверхностный размер структуры (Shallow Size) через unsafe.Sizeof:
	// =========================================================================
	// - Поле 'a' ([]int):  смещение 0,  размер 24 байта (байты 0..23)
	// - Поле 'b' (bool):   смещение 24, размер 1 байт   (байт 24)
	// - Padding (выравнивание): 3 байта пустоты         (байты 25..27)
	//   (Поле 'c' (int32) должно начинаться по адресу, кратному 4 байтам: 28 % 4 == 0)
	// - Поле 'c' (int32):  смещение 28, размер 4 байта   (байты 28..31)
	// - Поле 'd' (string): смещение 32, размер 16 байт  (байты 32..47)
	//
	// Итого размер заголовка структуры в памяти: 24 + 1 + 3 + 4 + 16 = 48 байт.
	fmt.Printf("Поверхностный размер структуры example (unsafe.Sizeof): %d байт\n", unsafe.Sizeof(example{}))

	// =========================================================================
	// 2. Глубокий размер (Deep Size) через библиотеку size.Of:
	// =========================================================================
	// Функция size.Of рекурсивно обходит указатели, срезы и строки:
	//
	// Структура ex:
	//   - Заголовок самой структуры:                 48 байт
	//   - Выделенный базовый массив среза a:        3 * 8 = 24 байта (3 элемента int)
	//   - Базовый массив байт строки d ("1234"):     4 байта (4 символа ASCII)
	//   -----------------------------------------------------------------------
	//   Итого:                                       48 + 24 + 4 = 76 байт
	ex := example{
		a: []int{1, 2, 3}, // срез из 3 элементов int
		b: true,           // 1 байт
		d: "1234",         // 4 байта данных строки
	}
	fmt.Println("Размер в байтах для ex (size.Of):", size.Of(ex))

	// Структура ex1:
	// В Go поля структур всегда занимают выделенное под них место в памяти,
	// независимо от того, заданы ли они явно (c: 100) или имеют значение по умолчанию (c: 0).
	// Поэтому размер ex1 в точности равен размеру ex: 76 байт!
	ex1 := example{
		a: []int{1, 2, 3},
		b: true,
		d: "1234",
		c: 100, // Значение 100 записано в те же 4 байта, где в ex был 0
	}
	fmt.Println("Размер в байтах для ex1 (size.Of):", size.Of(ex1))
}

