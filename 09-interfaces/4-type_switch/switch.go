// Package main демонстрирует работу конструкции Type Switch в Go:
// определение динамического типа значения, скрытого за интерфейсом (any).
package main

import (
	"fmt"
	"strings"
)

func main() {
	// Срез элементов произвольных типов (any / interface{})
	slice := []any{
		42,
		"golang",
		true,
		3.14159,
		nil,
		[]int{1, 2, 3},
	}

	for i, v := range slice {
		fmt.Printf("[%d] Значение: %-10v -> ", i, v)

		// КЛЮЧЕВОЙ МОМЕНТ:
		// Конструкция switch val := v.(type) объявляет локальную переменную val.
		// Внутри каждой ветки case тип переменной val сужается до конкретного объявленного типа!
		switch val := v.(type) {
		case int:
			// Здесь val имеет статический тип int, с ним можно выполнять арифметику
			fmt.Printf("Целое число (int), удвоенное: %d\n", val*2)

		case string:
			// Здесь val имеет статический тип string, доступны методы строк
			fmt.Printf("Строка (string), в верхнем регистре: %s\n", strings.ToUpper(val))

		case bool:
			// Здесь val имеет тип bool
			fmt.Printf("Булево значение (bool), отрицание: %t\n", !val)

		case float64:
			// Здесь val имеет тип float64
			fmt.Printf("Вещественное число (float64): %.2f\n", val)

		case nil:
			// Ветка для проверки неинициализированного/nil интерфейса
			fmt.Println("Значение равно nil (отсутствует)")

		default:
			// Если тип не подошел ни под одну ветку, val сохраняет тип any
			fmt.Printf("Неизвестный/другой тип (%T)\n", val)
		}
	}

	// Обратите внимание: группировка типов в одном case
	// case int, int32, int64:
	// При группировке нескольких типов в одной строке переменная val
	// сохраняет исходный интерфейсный тип (any), так как компилятор не может выбрать один тип.
}

