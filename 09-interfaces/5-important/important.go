// Package important содержит каталог важнейших интерфейсов стандартной библиотеки Go,
// иллюстрируя их контракты и философию проектирования.
//
// КЛЮЧЕВЫЕ ПОСЛОВИЦЫ GO (Go Proverbs):
//  1. "The bigger the interface, the weaker the abstraction."
//     (Чем больше интерфейс, тем слабее абстракция — стремитесь к интерфейсам из 1-2 методов).
//  2. "Don't design with interfaces, discover them."
//     (Не проектируйте интерфейсы заранее — объявляйте их там, где они требуются потребителю).
//  3. По соглашению об именовании, интерфейсы из одного метода получают суффикс "-er":
//     Reader, Writer, Closer, Stringer, Formatter, Marshaler.
package important

import (
	"fmt"
	"time"
)

// E — пользовательский пример реализации встроенного интерфейса error.
type E struct {
	code int
	msg  string
}

// Error выполняет контракт интерфейса builtin.error.
func (e *E) Error() string {
	return e.msg + fmt.Sprintf(": %v", e.code)
}

// ----------------------------------------------------------------------------
// 1. Встроенный интерфейс языка (builtin)
// ----------------------------------------------------------------------------

// builtin (предопределенный глобальный идентификатор в Go):
// type error interface {
//     Error() string
// }
// Любой тип, имеющий метод Error() string, является ошибкой в Go!

// ----------------------------------------------------------------------------
// 2. Пакет io — базовый потоковый ввод-вывод
// ----------------------------------------------------------------------------

// Reader — фундаментальный контракт на чтение потока байт.
// Правило контракта io.Reader:
// Если при чтении достигнут конец данных, Read может вернуть n > 0 байт и err == io.EOF,
// либо n > 0 и err == nil, а ошибку io.EOF вернуть при следующем вызове.
// Вызывающий код ОБЯЗАН сначала обработать прочитанные n байт, и только затем проверять err!
type Reader interface {
	Read(p []byte) (n int, err error)
}

// Writer — фундаментальный контракт на запись потока байт.
// Write обязан вернуть ошибку, если записано меньше len(p) байт.
type Writer interface {
	Write(p []byte) (n int, err error)
}

// Closer — контракт на освобождение ресурсов (файлов, сокетов, транзакций).
type Closer interface {
	Close() error
}

// Композиция интерфейсов (Interface Embedding):
// Интерфейсы в Go легко комбинируются:
type ReadWriter interface {
	Reader
	Writer
}

type ReadCloser interface {
	Reader
	Closer
}

// ----------------------------------------------------------------------------
// 3. Пакет sort — контракт сортировки коллекций
// ----------------------------------------------------------------------------

// sort.Interface позволяет сортировать произвольные коллекции с помощью sort.Sort().
// Достаточно реализовать:
//  - Len(): размер коллекции
//  - Less(i, j): истинно, если элемент i должен предшествовать j
//  - Swap(i, j): поменять элементы местами
type Interface interface {
	Len() int
	Less(i, j int) bool
	Swap(i, j int)
}

// ----------------------------------------------------------------------------
// 4. Пакет fmt — строковое представление
// ----------------------------------------------------------------------------

// Stringer позволяет объекту управлять своим строковым выводом в fmt.Print, fmt.Sprintf("%v").
type Stringer interface {
	String() string
}

// ----------------------------------------------------------------------------
// 5. Пакет net — сетевые соединения
// ----------------------------------------------------------------------------

// Conn — абстракция двунаправленного потокового сетевого соединения (TCP, Unix socket и др.).
type Conn interface {
	Read(b []byte) (n int, err error)
	Write(b []byte) (n int, err error)
	Close() error
	LocalAddr() Addr
	RemoteAddr() Addr
	SetDeadline(t time.Time) error
	SetReadDeadline(t time.Time) error
	SetWriteDeadline(t time.Time) error
}

// Listener — сетевой слушатель (сервер), принимающий входящие соединения.
type Listener interface {
	Accept() (Conn, error)
	Close() error
	Addr() Addr
}

// ----------------------------------------------------------------------------
// 6. Пакет net/http — HTTP-серверы и маршрутизация
// ----------------------------------------------------------------------------

// Handler — ключевой строительный блок веб-приложений на Go.
// Любая структура, имеющая метод ServeHTTP, может быть HTTP-обработчиком.
type Handler interface {
	ServeHTTP(ResponseWriter, *Request)
}

// ResponseWriter — интерфейс формирования HTTP-ответа клиенту.
type ResponseWriter interface {
	Header() Header
	Write([]byte) (int, error)
	WriteHeader(statusCode int)
}

// ----------------------------------------------------------------------------
// 7. Пакет encoding/json — кастомная сериализация
// ----------------------------------------------------------------------------

// Marshaler позволяет типу определить собственный формат сериализации в JSON.
type Marshaler interface {
	MarshalJSON() ([]byte, error)
}

// Вспомогательные типы для компиляции учебного файла
type Header int
type Addr int
type Request int

