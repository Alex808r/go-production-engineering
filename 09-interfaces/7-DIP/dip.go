// Package dip демонстрирует применение принципа инверсии зависимостей
// (Dependency Inversion Principle — буква 'D' в SOLID) на языке Go.
//
// ФОРМУЛИРОВКА ПРИНЦИПА:
//  1. Модули верхних уровней (бизнес-логика) не должны зависеть от модулей нижних уровней (БД, сеть, диск).
//     Оба должны зависеть от абстракций (интерфейсов).
//  2. Абстракции не должны зависеть от деталей. Детали должны зависеть от абстракций.
//
// ЗОЛОТОЕ ПРАВИЛО GO:
// "Accept interfaces, return structs." (Принимайте интерфейсы, возвращайте структуры).
// Интерфейсы объявляются на стороне потребителя (consumer-driven), а не реализации.
package dip

// Book — сущность предметной области (доменная модель).
type Book struct {
	ID    int
	Title string
}

// Storage — интерфейс, часть слоя бизнес-логики.
// Объявляет только те методы, которые реально требуются серверу.
// Сервер не знает, где физически хранятся книги (Postgres, MongoDB, файл или память).
type Storage interface {
	Books() []Book
}

// DB — конкретная реализация хранилища (деталь реализации нижнего уровня).
// Она неявно реализует интерфейс Storage.
type DB struct {
	data []Book
}

// NewDB создает конкретное подключение к базе данных.
func NewDB(books ...Book) *DB {
	return &DB{data: books}
}

// Books возвращает список книг из базы данных.
func (db *DB) Books() []Book {
	return db.data
}

// ============================================================================
// ПЛОХО: Нарушение принципа DIP (жесткая связанность)
// ============================================================================

// WrongServer напрямую зависит от конкретной структуры *DB.
// Недостатки:
//  1. Невозможно протестировать бизнес-логику в юнит-тестах без поднятия реальной БД.
//  2. Любое изменение внутренней структуры DB ломает WrongServer.
//  3. Невозможно без переписывания заменить БД на кэш Redis или другое хранилище.
type WrongServer struct {
	db *DB // Прямая зависимость от детали реализации!
}

func (s *WrongServer) BusinessLogic() []Book {
	// Жесткая привязка к конкретной структуре
	return s.db.Books()
}

// ============================================================================
// ХОРОШО: Соблюдение принципа DIP (слабая связанность)
// ============================================================================

// GoodServer зависит от абстракции Storage, а не от конкретной реализации.
// Преимущества:
//  1. Полная изоляция бизнес-логики от деталей ввода-вывода.
//  2. Легко тестируется с помощью моков (mockStorage) без базы данных.
//  3. Реализацию можно заменить в main() без правки кода GoodServer.
type GoodServer struct {
	db Storage // Зависимость от интерфейса!
}

// NewGoodServer — конструктор с внедрением зависимости (Dependency Injection).
func NewGoodServer(s Storage) *GoodServer {
	return &GoodServer{db: s}
}

// BusinessLogic выполняет доменную логику, работая только с контрактом Storage.
func (s *GoodServer) BusinessLogic() []Book {
	return s.db.Books()
}

