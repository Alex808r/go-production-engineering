// Package main демонстрирует использование неблокирующей атомарной синхронизации (lock-free)
// с помощью стандартного пакета sync/atomic (типы Go 1.19+: atomic.Int64, atomic.Bool).
package main

import (
	"fmt"
	"sync"
	"sync/atomic"
)

func main() {
	// ========================================================================
	// ТЕОРИЯ: АТОМАРНЫЕ ОПЕРАЦИИ (LOCK-FREE СИНХРОНИЗАЦИЯ)
	// ========================================================================
	// В отличие от sync.Mutex, который при конфликте переводит горутину в режим сна
	// и требует переключения контекста планировщика Go, пакет sync/atomic использует
	// аппаратные инструкции центрального процессора (CPU):
	//   - LOCK XADD (Fetch-and-Add)
	//   - CMPXCHG (Compare-And-Swap, CAS)
	//
	// Преимущества atomic:
	//  1. Экстремальная скорость (работает на уровне кэшей CPU L1/L2).
	//  2. Отсутствие блокировок (lock-free) и дедлоков.
	//
	// Когда использовать:
	//  - Высоконагруженные счетчики (запросы, метрики, активные соединения).
	//  - Булевы флаги состояния (atomic.Bool).
	//  - Атомарная замена указателя на конфиг (atomic.Pointer[T]).
	//
	// Когда НЕ использовать (нужен sync.Mutex):
	//  - Если нужно согласованно обновить несколько взаимосвязанных полей структуры.

	// atomic.Int64 — типобезопасная обертка над int64 (доступна с Go 1.19+)
	var counter atomic.Int64

	const N = 100_000
	var wg sync.WaitGroup

	wg.Add(N)
	for i := 0; i < N; i++ {
		go func() {
			defer wg.Done()
			// c.Add(1) атомарно инкрементирует значение без мьютекса
			counter.Add(1)
		}()
	}

	wg.Wait()

	// c.Load() атомарно вычитывает значение
	fmt.Println("Итоговый атомарный счётчик:", counter.Load())

	// Пример атомарного флага:
	var running atomic.Bool
	running.Store(true)
	fmt.Println("Флаг running:", running.Load())
	running.Store(false)
	fmt.Println("Флаг running после Store(false):", running.Load())
}

