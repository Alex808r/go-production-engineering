// Package main разбирает самые частые и опасные ошибки при работе с конкурентностью в Go:
// замыкания в циклах, псевдосинхронизацию через Sleep, утечки горутин (Goroutine Leaks) и дедлоки.
package main

import (
	"fmt"
	"sync"
	"time"
)

// ============================================================================
// ОШИБКА №1. Захват переменной цикла через замыкание (Loop Variable Capture)
// ============================================================================
// В версиях Go до 1.22 переменная `i` была ОДНОЙ на все итерации цикла.
// Запущенные горутины читали адрес одной и той же переменной, которая быстро
// добегала до 10, и все горутины выводили число 10 (или перемешанные числа).
// В Go 1.22+ область видимости `i` стала per-iteration, но правилом хорошего тона
// остаётся явная передача переменной как аргумента: `go func(val int) { ... }(i)`.
func demoError1() {
	fmt.Println("--- 1. Правильный запуск горутин в цикле с аргументом ---")
	var wg sync.WaitGroup
	wg.Add(3)
	for i := 1; i <= 3; i++ {
		// Передаем i как аргумент val, создавая независимую копию значения
		go func(val int) {
			defer wg.Done()
			fmt.Printf("Итерация #%d\n", val)
		}(i)
	}
	wg.Wait()
}

// ============================================================================
// ОШИБКА №2. Использование time.Sleep вместо синхронизации
// ============================================================================
// Задержка time.Sleep(100*time.Millisecond) — ненадежный способ ожидания горутин.
// Под нагрузкой в CI/CD или на медленном сервере горутина может не успеть выполниться
// за отведенное время, приводя к плавающим («флакающим») тестам и потере данных.
// ПРАВИЛЬНО: всегда использовать sync.WaitGroup, errgroup или каналы.
func demoError2() {
	fmt.Println("\n--- 2. Синхронизация через sync.WaitGroup вместо time.Sleep ---")
	var wg sync.WaitGroup
	wg.Add(3)
	for i := 1; i <= 3; i++ {
		go func(val int) {
			defer wg.Done()
			fmt.Printf("Безопасное выполнение задачи #%d\n", val)
		}(i)
	}
	wg.Wait()
}

// ============================================================================
// ОШИБКА №3. Утечка горутин (Goroutine Leak)
// ============================================================================
// Если горутина блокируется на записи в небуферизованный канал, из которого
// никто никогда не прочитает (или на чтении из канала, куда никто не напишет),
// она зависает в памяти НАВСЕГДА. Сборщик мусора (GC) НЕ может удалить заблокированную горутину!
// Со временем память процесса истощается (OOM).
// ПРАВИЛЬНО: использовать context.Context для отмены или буферизованные каналы достаточного размера.
func demoError3() {
	fmt.Println("\n--- 3. Предотвращение утечки горутины через буферизованный канал ---")
	// Если нам нужен только ПЕРВЫЙ ответивший сервис (паттерн First Response):
	// Канал ОБЯЗАН иметь буфер минимум 2, чтобы вторая (проигравшая) горутина
	// смогла записать результат в буфер и завершиться, а не осталась висеть в памяти!
	ch := make(chan string, 2)

	go func() {
		time.Sleep(20 * time.Millisecond)
		ch <- "ответ от быстрого сервера"
	}()
	go func() {
		time.Sleep(100 * time.Millisecond)
		ch <- "ответ от медленного сервера" // запишет в буфер и мирно завершится!
	}()

	firstResponse := <-ch
	fmt.Println("Получен первый ответ:", firstResponse)
}

func main() {
	demoError1()
	demoError2()
	demoError3()
}

