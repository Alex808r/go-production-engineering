package guitar

import (
	"fmt"
)

// Guitar представляет гитару как объект с характеристиками и репертуаром (табулатурами).
//
// ИНКАПСУЛЯЦИЯ В GO:
// Поля manufacturer и model начинаются со строчной буквы — они неэкспортируемые (private)
// и доступны только внутри пакета guitar.
// Поле Tabs экспортируемое (public), так как начинается с заглавной буквы.
type Guitar struct {
	manufacturer string
	model        string

	Tabs map[string]string
}

// New — идиоматичная функция-конструктор для типа Guitar.
//
// ПОЧЕМУ В GO НУЖНЫ ФУНКЦИИ-КОНСТРУКТОРЫ:
// 1. Отсутствие классов: В Go нет ключевого слова class и встроенных конструкторов (как __init__ в Python
//    или constructor в TS/C++). Инициализация объектов выполняется обычными фабричными функциями.
// 2. Именование по Effective Go: Если пакет называется guitar, функция называется New(),
//    а не NewGuitar(), чтобы при вызове из другого пакета не было тавтологии: guitar.New(), а не guitar.NewGuitar().
// 3. Защита от паники на nil-map:
//    Zero value для map в Go — это nil.
//    Чтение из nil-мапы разрешено (возвращает zero-value типа значения), но запись в нее
//    немедленно вызывает фатальную панику: `panic: assignment to entry in nil map`.
//    Конструктор New гарантирует выделение памяти под мапу через make(map[string]string).
// 4. Возврат указателя (*Guitar):
//    - Позволяет методам модифицировать исходный экземпляр без копирования всего объекта.
//    - Объекты, представляющие сущности предметной области со сложным состоянием, принято
//      создавать и передавать по указателю.
func New(manufacturer, model string) *Guitar {
	// В литерале структуры слева от двоеточия указано поле структуры,
	// а справа — локальный параметр функции. В Go они не конфликтуют.
	g := Guitar{
		manufacturer: manufacturer,
		model:        model,
	}

	// Инициализация внутренней хэш-таблицы (предотвращает nil map panic)
	g.Tabs = make(map[string]string)

	// В Go компилятор выполняет Escape Analysis: переменная g аллоцируется в куче (heap),
	// поэтому возврат локального адреса &g абсолютно безопасен (в отличие от C/C++).
	return &g
}

// Info возвращает форматированные сведения о гитаре.
// Принимает получатель по указателю (g *Guitar), следуя единому стилю API структуры.
func (g *Guitar) Info() string {
	return fmt.Sprintf("Гитара %s %s", g.manufacturer, g.model)
}

