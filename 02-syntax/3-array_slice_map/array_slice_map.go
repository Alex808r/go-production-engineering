package main

import "fmt"

func main() {
	var array = [...]int{1, 2, 3, 4, 5} // массив
	slice := []int{0, 1, 2, 3, 4, 5}    // слайс
	slice = append(slice, 10)

	fmt.Println(slice[1:4])

	_ = slice[len(slice)-1]
	fmt.Println("array", array, len(array), cap(array))
	fmt.Println("slice", slice, len(slice), cap(slice))

	slice = make([]int, 10, 20)
	fmt.Println("\nslice после инициализации:", slice, len(slice), cap(slice))

	// ассоциативный массив
	var m map[int]string
	//m[3] = "ABC" // panic: assignment to entry in nil map
	//m = make(map[int]string)
	m = map[int]string{}
	m[3] = "ABC"
	m[6] = "DEF"
	for k, v := range m {
		fmt.Printf("ключ %d, значение %s\n", k, v)
	}
}

// sliceDimensions демонстрирует механизм и динамику автоматического роста вместимости (cap) среза:
//  1. Реаллокация базового массива: при нехватке места append выделяет новый массив большего размера и копирует данные.
//  2. Коэффициент роста:
//     - До 256 элементов (threshold в runtime начиная с Go 1.18, ранее было 1024) емкость строго удваивается (коэффициент 2.0).
//     - Свыше 256 элементов рантайм плавно снижает коэффициент масштабирования по формуле
//       newcap += (newcap + 3*threshold) / 4, приближая его к ~1.25 для экономии памяти.
//  3. Влияние аллокатора: значения cap дополнительно округляются под размерные классы памяти (size classes) рантайма Go.
func sliceDimensions() {
	var slice []int
	c := cap(slice)
	for i := 0; i < 1_000_000; i++ {
		slice = append(slice, i)
		if cap(slice) != c {
			fmt.Printf("длина: %v\tемкость:%v\tкоэффициент:%v\n", len(slice), cap(slice), float64(cap(slice))/float64(c))
			c = cap(slice)
		}
	}
}

